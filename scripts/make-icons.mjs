// Draws Waypoint's icon (amber diamond on a dark rounded square) without any image libraries:
// writes build/icon.png + build/icon.ico (installer/exe) and src/main/iconData.ts (window/tray).
// Run: node scripts/make-icons.mjs
import { deflateSync } from 'zlib'
import { mkdirSync, writeFileSync } from 'fs'

const BG = [0x17, 0x18, 0x1b]
const ACCENT = [0xe6, 0xaa, 0x50]
const SS = 4 // supersampling for smooth edges

function draw(size, { background = true } = {}) {
  const px = new Uint8Array(size * size * 4)
  const r = size * 0.22 // corner radius
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let bg = 0
      let fg = 0
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const fx = x + (sx + 0.5) / SS
          const fy = y + (sy + 0.5) / SS
          // rounded square
          const dx = Math.max(r - fx, fx - (size - r), 0)
          const dy = Math.max(r - fy, fy - (size - r), 0)
          if (dx * dx + dy * dy <= r * r) bg++
          // diamond: |x-c| + |y-c| <= k
          const c = size / 2
          if (Math.abs(fx - c) + Math.abs(fy - c) <= size * 0.3) fg++
        }
      }
      const n = SS * SS
      const a = background ? bg / n : fg / n
      const f = fg / n
      const i = (y * size + x) * 4
      for (let k = 0; k < 3; k++) px[i + k] = Math.round(background ? BG[k] * (1 - f) + ACCENT[k] * f : ACCENT[k])
      px[i + 3] = Math.round(a * 255)
    }
  }
  return png(size, px)
}

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
function crc32(buf) {
  let c = 0xffffffff
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length)
  out.writeUInt32BE(data.length, 0)
  out.write(type, 4, 'ascii')
  Buffer.from(data).copy(out, 8)
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length)
  return out
}
function png(size, rgba) {
  const raw = Buffer.alloc(size * (size * 4 + 1))
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0 // filter: none
    Buffer.from(rgba.subarray(y * size * 4, (y + 1) * size * 4)).copy(raw, y * (size * 4 + 1) + 1)
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ])
}

/** ICO holding PNG images (supported since Windows Vista) */
function ico(images) {
  const header = Buffer.alloc(6 + images.length * 16)
  header.writeUInt16LE(0, 0)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  let offset = header.length
  images.forEach(({ size, data }, i) => {
    const e = 6 + i * 16
    header[e] = size >= 256 ? 0 : size
    header[e + 1] = size >= 256 ? 0 : size
    header.writeUInt16LE(1, e + 4) // planes
    header.writeUInt16LE(32, e + 6) // bpp
    header.writeUInt32LE(data.length, e + 8)
    header.writeUInt32LE(offset, e + 12)
    offset += data.length
  })
  return Buffer.concat([header, ...images.map((i) => i.data)])
}

mkdirSync('build', { recursive: true })
const sizes = [16, 24, 32, 48, 64, 128, 256]
const images = sizes.map((size) => ({ size, data: draw(size) }))
writeFileSync('build/icon.png', images.at(-1).data)
writeFileSync('build/icon.ico', ico(images))
// Tray: just the diamond (reads better on the taskbar), 16 and 32 px for 100%/200% scaling
const tray16 = draw(16, { background: false }).toString('base64')
const tray32 = draw(32, { background: false }).toString('base64')
const app256 = images.at(-1).data.toString('base64')
writeFileSync(
  'src/main/iconData.ts',
  `// Generated by scripts/make-icons.mjs, do not edit by hand.\n` +
    `export const APP_ICON_PNG = 'data:image/png;base64,${app256}'\n` +
    `export const TRAY_ICON_PNG = 'data:image/png;base64,${tray16}'\n` +
    `export const TRAY_ICON_PNG_2X = 'data:image/png;base64,${tray32}'\n`
)
console.log('icons written')
